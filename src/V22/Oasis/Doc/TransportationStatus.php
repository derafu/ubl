        $this->statusPeriods[] = $item;
        return $this;
    }

    /**
     * @param list<mixed> $values
     */
    private static function validateStatusPeriods(array $values): void
    {
        foreach ($values as $value) {
            if (!$value instanceof Period) {
                throw new \InvalidArgumentException(
                    sprintf('Expected instance of Period, got %s', get_debug_type($value)),
                );
            }
        }
    }
