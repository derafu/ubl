     * @param list<mixed> $values
     */
    private static function validateSignatures(array $values): void
    {
        foreach ($values as $value) {
            if (!$value instanceof Signature) {
                throw new \InvalidArgumentException(
                    sprintf('Expected instance of Signature, got %s', get_debug_type($value)),
                );
            }
        }
    }
